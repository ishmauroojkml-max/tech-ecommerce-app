/*
# Create the NexaTech store backend

1. New Tables
- `profiles`: one safe, non-secret profile row per Supabase Auth user. Stores display name and an operator-controlled role.
- `products`: the public catalog, including sale pricing, ratings, product imagery, and active status.
- `orders`: completed checkout records owned by the signed-in customer, with server-calculated totals and item snapshots.

2. Authentication
- Supabase Auth remains the source of truth for identities and passwords.
- A trigger creates a profile automatically whenever a new Auth user signs up.

3. Security
- Row Level Security is enabled on every new table.
- Anyone may read active products; only profiles with the immutable `admin` role may create, edit, or remove products.
- Customers may read only their own orders; admins may read all orders.
- Customers cannot directly insert order totals or item prices. The `create_order` function looks up current product prices, validates quantities, recalculates the total, and stores the order atomically.
- Profile roles are not client-writable. Display names are the only profile field users may update.

4. Important notes
- Email confirmation is not changed by this migration; the application uses Supabase Auth email/password methods.
- To grant admin access, an operator must set a profile role to `admin` outside the customer-facing UI.
- The migration is idempotent and safe to apply again.
*/

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL,
  price numeric(12,2) NOT NULL CHECK (price >= 0),
  original_price numeric(12,2) NOT NULL CHECK (original_price >= price),
  rating numeric(2,1) NOT NULL DEFAULT 5 CHECK (rating >= 0 AND rating <= 5),
  reviews integer NOT NULL DEFAULT 0 CHECK (reviews >= 0),
  image text NOT NULL,
  badge text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  email text NOT NULL,
  items jsonb NOT NULL CHECK (jsonb_typeof(items) = 'array'),
  total numeric(12,2) NOT NULL CHECK (total > 0),
  status text NOT NULL DEFAULT 'Paid' CHECK (status IN ('Paid', 'Processing', 'Shipped', 'Cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS products_active_category_idx ON public.products (active, category);
CREATE INDEX IF NOT EXISTS orders_user_created_idx ON public.orders (user_id, created_at DESC);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

GRANT SELECT, UPDATE (display_name) ON public.profiles TO authenticated;
GRANT SELECT ON public.products TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.products TO authenticated;
GRANT SELECT ON public.orders TO authenticated;

DROP POLICY IF EXISTS "profiles_select_own" ON public.profiles;
CREATE POLICY "profiles_select_own" ON public.profiles FOR SELECT TO authenticated USING (auth.uid() = id OR EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));
DROP POLICY IF EXISTS "profiles_update_own_name" ON public.profiles;
CREATE POLICY "profiles_update_own_name" ON public.profiles FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "products_select_active" ON public.products;
CREATE POLICY "products_select_active" ON public.products FOR SELECT TO anon, authenticated USING (active OR EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));
DROP POLICY IF EXISTS "products_insert_admin" ON public.products;
CREATE POLICY "products_insert_admin" ON public.products FOR INSERT TO authenticated WITH CHECK (EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));
DROP POLICY IF EXISTS "products_update_admin" ON public.products;
CREATE POLICY "products_update_admin" ON public.products FOR UPDATE TO authenticated USING (EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin')) WITH CHECK (EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));
DROP POLICY IF EXISTS "products_delete_admin" ON public.products;
CREATE POLICY "products_delete_admin" ON public.products FOR DELETE TO authenticated USING (EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));

DROP POLICY IF EXISTS "orders_select_own_or_admin" ON public.orders;
CREATE POLICY "orders_select_own_or_admin" ON public.orders FOR SELECT TO authenticated USING (auth.uid() = user_id OR EXISTS (SELECT 1 FROM public.profiles AS admin_profile WHERE admin_profile.id = auth.uid() AND admin_profile.role = 'admin'));

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'name', ''))
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.create_order(p_items jsonb)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  item jsonb;
  product_row public.products%ROWTYPE;
  quantity integer;
  order_id uuid;
  calculated_total numeric(12,2) := 0;
  snapshots jsonb := '[]'::jsonb;
  customer_email text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Order must contain at least one product';
  END IF;
  SELECT email INTO customer_email FROM auth.users WHERE id = auth.uid();
  FOR item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    IF NOT (item ? 'id') OR NOT (item ? 'quantity') OR (item->>'id') !~ '^\\d+$' OR (item->>'quantity') !~ '^\\d+$' THEN
      RAISE EXCEPTION 'Invalid order item';
    END IF;
    quantity := (item->>'quantity')::integer;
    IF quantity < 1 OR quantity > 100 THEN
      RAISE EXCEPTION 'Invalid quantity';
    END IF;
    SELECT * INTO product_row FROM public.products WHERE id = (item->>'id')::bigint AND active = true;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product unavailable';
    END IF;
    calculated_total := calculated_total + (product_row.price * quantity);
    snapshots := snapshots || jsonb_build_array(jsonb_build_object('id', product_row.id, 'name', product_row.name, 'price', product_row.price, 'quantity', quantity, 'image', product_row.image));
  END LOOP;
  INSERT INTO public.orders (user_id, email, items, total)
  VALUES (auth.uid(), COALESCE(customer_email, ''), snapshots, calculated_total)
  RETURNING id INTO order_id;
  RETURN order_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.create_order(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_order(jsonb) TO authenticated;
